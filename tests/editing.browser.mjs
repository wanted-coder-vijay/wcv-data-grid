import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir } from 'node:fs/promises'
await mkdir('evidence', { recursive: true })
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true })
const page = await browser.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
const url = `${process.env.EDITING_BASE_URL || 'http://127.0.0.1:5181'}/tests/editing.html`
const check = async (condition, description) => {
  await page.waitForFunction(condition)
  console.log(`PASS ${description}`)
}
try {
  await page.goto(url)
  await page.getByRole('button', { name: 'Open row actions' }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  const name = page.locator('tbody input[type=text]')
  await name.fill('')
  await page.getByRole('button', { name: 'Save row' }).click()
  await page.getByText('Name is required.', { exact: true }).waitFor()
  assert.equal(await name.getAttribute('aria-invalid'), 'true')
  assert.equal(await page.getByTestId('calls').textContent(), '0')
  console.log('PASS invalid row does not invoke persistence and marks field')
  await name.fill('Retained draft')
  await page.getByLabel('Fail saves').evaluate(input => { if (!input.checked) input.click() })
  await page.getByRole('button', { name: 'Save row' }).click()
  assert.equal(await name.isDisabled(), true)
  assert.equal(await page.getByRole('button', { name: 'Cancel edit' }).isDisabled(), true)
  await page.getByText('Could not save changes. Try again.', { exact: true }).waitFor()
  assert.equal(await name.inputValue(), 'Retained draft')
  await page.screenshot({ path: 'evidence/async-editing-failed-save.png', fullPage: true })
  assert.equal(await page.getByTestId('calls').textContent(), '1')
  console.log('PASS failed row save retains draft and pending controls lock')
  await page.getByLabel('Fail saves').evaluate(input => { if (input.checked) input.click() })
  await page.getByRole('button', { name: 'Save row' }).click()
  await check(() => document.querySelectorAll('tbody input').length === 0, 'successful retry exits editing')
  assert.match(await page.locator('tbody').textContent(), /Retained draft/)
  assert.equal(await page.getByTestId('calls').textContent(), '2')
  await page.getByText('Retained draft', { exact: true }).dblclick()
  await name.fill('')
  await name.press('Enter')
  await page.getByText('Name is required.', { exact: true }).waitFor()
  assert.equal(await page.getByTestId('calls').textContent(), '2')
  console.log('PASS invalid single-cell edit never saves')
  await page.getByLabel('Fail saves').evaluate(input => { if (!input.checked) input.click() })
  await name.fill('Cell retry')
  await name.press('Enter')
  await page.getByText('Could not save changes. Try again.', { exact: true }).waitFor()
  assert.equal(await name.inputValue(), 'Cell retry')
  await page.getByLabel('Fail saves').evaluate(input => { if (input.checked) input.click() })
  await name.press('Enter')
  await check(() => document.querySelectorAll('tbody input').length === 0, 'cell retry succeeds')
  assert.equal(await page.getByTestId('calls').textContent(), '4')
  await page.getByText('Cell retry', { exact: true }).dblclick()
  await name.fill('Canceled')
  await name.press('Escape')
  await check(() => document.querySelectorAll('tbody input').length === 0, 'Escape closes editor')
  assert.equal(await page.getByTestId('calls').textContent(), '4')
  assert.match(await page.locator('tbody').textContent(), /Cell retry/)
  await page.getByLabel('Synchronous saves').check()
  await page.getByLabel('Fail saves').check()
  await page.getByRole('button', { name: 'Open row actions' }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await name.fill('Sync draft')
  await page.getByRole('button', { name: 'Save row' }).click()
  await page.getByText('Could not save changes. Try again.', { exact: true }).waitFor()
  assert.equal(await name.inputValue(), 'Sync draft')
  await page.getByLabel('Fail saves').evaluate(input => input.click())
  await page.getByRole('button', { name: 'Save row' }).click()
  await check(() => document.querySelectorAll('tbody input').length === 0, 'synchronous failure and retry retain compatibility')
  assert.equal(await page.getByTestId('calls').textContent(), '6')
  await page.getByRole('button', { name: 'Open row actions' }).click()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  await name.fill('Discarded row draft')
  await page.getByRole('button', { name: 'Cancel edit' }).click()
  assert.equal(await page.getByTestId('calls').textContent(), '6')
  assert.match(await page.locator('tbody').textContent(), /Sync draft/)
  console.log('PASS row cancellation does not persist its draft')
  assert.deepEqual(errors, [])
  await page.screenshot({ path: 'evidence/async-editing-verified.png', fullPage: true })
  console.log('PASS canceled cell never saves; no browser errors')
} catch (error) {
  console.log(await page.locator('body').innerText())
  console.log('inputs', await page.locator('input').evaluateAll(inputs => inputs.map(input => ({ value: input.value, checked: input.checked, disabled: input.disabled }))))
  throw error
} finally { await browser.close() }
