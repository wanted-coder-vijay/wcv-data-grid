import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir } from 'node:fs/promises'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1214, height: 884 } })
const base = process.env.DETAILS_BASE_URL || 'http://127.0.0.1:5189'
const errors = []; page.on('pageerror', error => errors.push(error.message))
await mkdir('evidence', { recursive: true })
async function viewFirst() {
  const menu = page.getByRole('button', { name: 'Open row actions', exact: true }).first()
  await menu.scrollIntoViewIfNeeded()
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await menu.click(); await page.getByRole('button', { name: 'View', exact: true }).click()
  await page.getByRole('dialog').waitFor()
}
try {
  await page.goto(base + '/playground?config=' + encodeURIComponent(JSON.stringify({ validation: true, asyncSaving: true, controlled: true, savedViews: true })))
  await page.getByRole('button', { name: 'Add row', exact: true }).waitFor()
  const style = await page.evaluate(() => ['.config-panel', '[data-grid-scrollbar]'].map(selector => {
    const el = document.querySelector(selector), css = getComputedStyle(el), bar = getComputedStyle(el, '::-webkit-scrollbar')
    return [css.scrollbarWidth, css.scrollbarColor, bar.width, bar.height]
  }))
  assert.deepEqual(style[0], style[1]); assert.equal(style[0][0], 'thin')
  await page.getByRole('button', { name: 'Add row', exact: true }).click()
  const draft = page.locator('tbody tr').filter({ has: page.getByRole('button', { name: 'Save row', exact: true }) })
  const id = (await draft.locator('td').nth(1).innerText()).trim()
  for (const input of await draft.locator('input:not([type=checkbox]), select').all()) assert.equal(await input.inputValue(), '')
  assert.equal(await draft.locator('[data-slot=select-trigger][data-placeholder]').count(), 2)
  assert.equal(await draft.getByRole('button', { name: 'Date editor: Due date', exact: true }).innerText(), 'Choose date')
  await page.getByRole('button', { name: 'Save row', exact: true }).click()
  await page.getByText('Project name is required.', { exact: true }).waitFor()
  await draft.locator('input[type=text]').first().fill('Blank draft persisted')
  await draft.locator('input[type=number]').fill('0')
  await page.getByLabel('Fail saves (drafts retained)').check()
  await page.getByRole('button', { name: 'Save row', exact: true }).click()
  await page.getByText('Could not save changes. Try again.', { exact: true }).waitFor()
  assert.equal(await draft.locator('input[type=text]').first().inputValue(), 'Blank draft persisted')
  await page.getByLabel('Fail saves (drafts retained)').uncheck()
  await page.getByRole('button', { name: 'Save row', exact: true }).click()
  await page.getByText('Row saved.', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Add row', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel edit', exact: true }).click()
  assert.equal(await page.getByRole('button', { name: 'Save row', exact: true }).count(), 0)
  await page.getByRole('button', { name: 'Open search', exact: true }).click()
  await page.getByPlaceholder('Search...', { exact: true }).fill('no matching project 98765')
  await page.getByRole('button', { name: 'Add row', exact: true }).click()
  await page.getByRole('button', { name: 'Save row', exact: true }).waitFor()
  assert.equal(await page.getByPlaceholder('Search...', { exact: true }).inputValue(), '')
  await page.getByRole('button', { name: 'Cancel edit', exact: true }).click()
  // Show all records to verify insertion exactly once.
  await page.getByLabel('Pagination', { exact: true }).uncheck()
  assert.equal(await page.getByText(id, { exact: true }).count(), 1)
  assert.equal(await page.getByText('Blank draft persisted', { exact: true }).count(), 1)
  assert.equal(await page.locator('tbody tr').count(), 49)
  console.log('PASS matching scrollbars, blank fields, validation, failed-save retention, single insertion and draft cancellation')
  await viewFirst()
  let dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Edit record', exact: true }).waitFor()
  await dialog.getByRole('button', { name: 'Delete record', exact: true }).waitFor()
  const bounds = await dialog.boundingBox(); assert.ok(bounds.width <= 580)
  await page.screenshot({ path: 'evidence/details-redesign.png' })
  await dialog.getByRole('button', { name: 'Edit record', exact: true }).click()
  await page.getByRole('button', { name: 'Save row', exact: true }).waitFor()
  await page.getByRole('button', { name: 'Cancel edit', exact: true }).click()
  await viewFirst()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete record', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  assert.equal(await page.locator('tbody tr').count(), 49)
  await viewFirst()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete record', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Delete', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('tbody tr').length === 48)
  await page.getByLabel('Details panel: Edit action', { exact: true }).uncheck()
  await page.getByLabel('Details panel: Delete action', { exact: true }).uncheck()
  await page.getByLabel('Details layout', { exact: true }).selectOption('comfy')
  await viewFirst(); dialog = page.getByRole('dialog')
  assert.equal(await dialog.getByRole('button', { name: 'Edit record', exact: true }).count(), 0)
  assert.equal(await dialog.getByRole('button', { name: 'Delete record', exact: true }).count(), 0)
  assert.equal(await dialog.getByRole('tab', { name: 'Comfy', exact: true }).getAttribute('aria-selected'), 'true')
  await page.setViewportSize({ width: 390, height: 844 })
  const mobile = await dialog.boundingBox(); assert.ok(mobile.width <= 390)
  await dialog.getByRole('button', { name: 'Close details', exact: true }).waitFor({ state: 'visible' })
  await page.screenshot({ path: 'evidence/details-mobile.png' })
  assert.deepEqual(errors, [])
  console.log('PASS redesigned details, inline Edit, configurable actions/density, responsive mobile panel')
} catch (error) { await page.screenshot({ path: 'evidence/details-failure.png' }); throw error }
finally { await browser.close() }
