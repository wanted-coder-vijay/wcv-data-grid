import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { mkdir } from 'node:fs/promises'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.STATE_BASE_URL || 'http://127.0.0.1:5186'
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true })
const page = await browser.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
const search = async () => { if (await page.getByRole('button', { name: 'Open search', exact: true }).isVisible()) await page.getByRole('button', { name: 'Open search', exact: true }).click(); return page.getByPlaceholder('Search...') }
const waitState = async (key, value) => page.waitForFunction(({ key, value }) => JSON.parse(document.querySelector('[data-testid=state]').textContent)[key] === value, { key, value })
try {
  if (!process.env.PUBLIC_ONLY) {
  await page.goto(base + '/tests/state.html')
  await (await search()).fill('Item 2')
  await waitState('globalFilter', 'Item 2')
  await page.waitForFunction(() => JSON.parse(document.querySelector('[data-testid=state]').textContent).pagination.pageIndex === 0)
  console.log('PASS controlled search and batched pagination reset compose')
  await page.getByRole('button', { name: 'External configuration', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('tbody').textContent.includes('Item 29'))
  assert.equal(await page.getByRole('columnheader', { name: 'Quantity' }).count(), 0)
  assert.equal(await (await search()).inputValue(), 'Item 2')
  await page.getByLabel('View name', { exact: true }).fill('Filtered projects')
  await page.getByRole('button', { name: 'Save view', exact: true }).click()
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('dynostack-state-test-v1')))
  assert.equal(stored.views.length, 1)
  for (const key of ['rowSelection', 'expanded', 'pagination', 'data']) assert.equal(key in stored.views[0].state, false)
  assert.deepEqual(stored.views[0].state.columnSizing, { name: 300 })
  assert.deepEqual(stored.views[0].state.columnPinning, { left: ['name'] })
  await page.getByRole('button', { name: 'Reset view', exact: true }).click()
  await waitState('globalFilter', '')
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await waitState('globalFilter', 'Item 2')
  const state = JSON.parse(await page.getByTestId('state').textContent())
  assert.deepEqual(state.rowSelection, { '2': true })
  assert.deepEqual(state.columnVisibility, { quantity: false })
  assert.deepEqual(state.sorting, [{ id: 'quantity', desc: true }])
  await page.getByLabel('View name', { exact: true }).fill('Renamed view')
  await page.getByRole('button', { name: 'Rename', exact: true }).click()
  assert.equal(await page.getByLabel('Choose saved view').inputValue(), stored.views[0].id)
  await page.reload()
  await page.getByLabel('Choose saved view').selectOption({ label: 'Renamed view' })
  await page.getByRole('button', { name: 'Restore', exact: true }).click()
  await waitState('globalFilter', 'Item 2')
  console.log('PASS save, snapshot scope, restore, reset, rename and reload persistence')
  await page.getByRole('button', { name: 'Delete view', exact: true }).click()
  assert.equal(await page.evaluate(() => localStorage.getItem('dynostack-state-test-v1')), null)
  await page.getByLabel('View name', { exact: true }).fill('To clear')
  await page.getByRole('button', { name: 'Save view', exact: true }).click()
  await page.getByRole('button', { name: 'Clear saved views', exact: true }).click()
  assert.equal(await page.evaluate(() => localStorage.getItem('dynostack-state-test-v1')), null)
  await page.evaluate(() => localStorage.setItem('dynostack-state-test-v1', '{bad json'))
  await page.reload()
  await page.getByRole('alert').waitFor()
  await page.getByRole('button', { name: 'Clear saved views', exact: true }).click()
  assert.equal(await page.getByRole('alert').count(), 0)
  console.log('PASS delete, clear persistence and malformed storage recovery')
  await page.getByLabel('Control mode').selectOption('readonly')
  await (await search()).fill('Ignored')
  assert.equal(await (await search()).inputValue(), '')
  await page.getByLabel('Control mode').selectOption('partial')
  await (await search()).fill('Item 3')
  await waitState('globalFilter', 'Item 3')
  assert.equal(await page.locator('tbody tr').count(), 1)
  console.log('PASS read-only and partial controlled state')
  }
  // Public playground integrations, including settings and retry without remounting.
  await page.goto(base + '/playground')
  await page.getByLabel('Required name & nonnegative budget').check()
  await page.getByLabel('Application controlled state').check()
  await page.getByLabel('Named saved views', { exact: true }).check()
  await page.getByLabel('Simulate 1.2-second saves').check()
  await page.getByLabel('Fail saves (drafts retained)').check()
  const cell = page.getByText('Website redesign', { exact: true }).first()
  await cell.dblclick()
  const editor = page.locator('tbody input[type=text]').first()
  await editor.fill('')
  await editor.press('Enter')
  await page.getByText('Project name is required.', { exact: true }).waitFor()
  await editor.fill('Retry playground draft')
  await editor.press('Enter')
  assert.equal(await editor.isDisabled(), true)
  assert.equal(await page.getByRole('button', { name: 'Save view', exact: true }).isDisabled(), true)
  await page.getByText('Could not save changes. Try again.', { exact: true }).waitFor()
  assert.equal(await editor.inputValue(), 'Retry playground draft')
  await page.getByLabel('Fail saves (drafts retained)').uncheck()
  await page.waitForFunction(() => !document.querySelector('tbody input[type=text]')?.disabled)
  await editor.press('Enter')
  await page.getByText('Retry playground draft', { exact: true }).waitFor()
  await page.getByLabel('View name', { exact: true }).fill('Public demo')
  await page.getByRole('button', { name: 'Save view', exact: true }).click()
  await page.getByRole('button', { name: 'Reset controlled state', exact: true }).click()
  await mkdir('evidence', { recursive: true })
  await page.screenshot({ path: 'evidence/playground-state-views.png', fullPage: true })
  await page.getByRole('button', { name: 'Code', exact: true }).click()
  assert.match(await page.locator('.code-preview pre').textContent(), /createDataTableState/)
  assert.match(await page.locator('.code-preview pre').textContent(), /savedViews/)
  assert.match(await page.locator('.code-preview pre').textContent(), /validate/)
  console.log('PASS public playground validation, pending state, failure retention, retry and generated configuration')
  assert.deepEqual(errors, [])
} catch (error) {
  console.log('Browser state at failure:', (await page.locator('body').innerText()).slice(-5000))
  throw error
} finally { await browser.close() }
