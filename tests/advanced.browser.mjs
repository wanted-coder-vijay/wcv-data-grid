import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { readFile, mkdir } from 'node:fs/promises'
import ExcelJS from 'exceljs'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.env.ADVANCED_BASE_URL || 'http://127.0.0.1:5188'
const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1214, height: 884 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await mkdir('evidence', { recursive: true })
try {
  await page.goto(base + '/playground?config=' + encodeURIComponent(JSON.stringify({ keyboard: true, validation: true, asyncSaving: true, controlled: true, savedViews: true })))
  assert.equal(await page.getByText('French toolbar labels', { exact: true }).count(), 0)
  await page.getByLabel('Expandable details', { exact: true }).check()
  await page.waitForFunction(() => document.querySelector('tbody tr td[data-nav-column=__expand] button')?.getAttribute('aria-label') === 'Expand row')
  await page.getByLabel('Expandable details', { exact: true }).uncheck()
  const nameCell = page.locator('[data-nav-row="PRJ-001"][data-nav-column="name"]')
  await nameCell.focus()
  await nameCell.press('ArrowDown')
  await page.waitForFunction(() => document.activeElement?.getAttribute('data-nav-row') === 'PRJ-002')
  await page.keyboard.press('ArrowUp')
  await page.keyboard.press('F2')
  const editor = page.locator('tbody input[type=text]').first()
  await editor.fill('Canceled keyboard draft')
  const outline = await editor.evaluate(input => getComputedStyle(input).outlineStyle)
  assert.equal(outline, 'none')
  await editor.press('Escape')
  await page.waitForFunction(() => document.activeElement?.getAttribute('data-nav-column') === 'name')
  await page.keyboard.press('Enter')
  await editor.fill('Keyboard saved')
  await editor.press('Tab')
  await page.getByText('Keyboard saved', { exact: true }).waitFor()
  await page.waitForFunction(() => document.activeElement?.getAttribute('data-nav-column') === 'owner')
  console.log('PASS expansion placement, no French toggle, subtle focus, arrows, F2, Escape and save-before-Tab')
  const actionMenu = page.getByRole('button', { name: 'Open row actions', exact: true }).first()
  await actionMenu.scrollIntoViewIfNeeded()
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await actionMenu.click()
  await page.getByRole('button', { name: 'Edit', exact: true }).click()
  const save = page.getByRole('button', { name: 'Save row', exact: true })
  const cancel = page.getByRole('button', { name: 'Cancel edit', exact: true })
  const saveBox = await save.boundingBox(), cancelBox = await cancel.boundingBox()
  assert.ok(Math.abs(saveBox.y - cancelBox.y) < 3)
  await page.getByLabel('Fail saves (drafts retained)').check()
  await save.click()
  await page.getByRole('button', { name: 'Saving…', exact: true }).waitFor()
  assert.equal(await cancel.isDisabled(), true)
  await page.screenshot({ path: 'evidence/edit-actions-saving.png', fullPage: true })
  assert.equal(await page.locator('button[aria-label="Saving…"] .animate-spin').count(), 1)
  await page.getByText('Could not save changes. Try again.', { exact: true }).waitFor()
  await page.screenshot({ path: 'evidence/edit-actions-failed.png', fullPage: true })
  await page.getByLabel('Fail saves (drafts retained)').uncheck()
  await page.getByRole('button', { name: 'Save row', exact: true }).click()
  await page.getByText('Row saved.', { exact: true }).waitFor()
  console.log('PASS horizontal edit actions, spinner, disabled cancellation, failed and successful save toasts')
  await page.getByLabel('Virtualize loaded rows', { exact: true }).check()
  await page.getByLabel('Sample rows', { exact: true }).selectOption('10000')
  await page.waitForFunction(() => document.querySelector('table[aria-label="Project workspace"]')?.getAttribute('aria-rowcount') === '10001')
  await page.waitForFunction(() => document.querySelectorAll('tbody tr[data-index]').length > 0 && document.querySelectorAll('tbody tr[data-index]').length < 80)
  const viewport = page.locator('div.overflow-auto').filter({ has: page.locator('table[aria-label="Project workspace"]') })
  await viewport.evaluate(element => { element.scrollTop = element.scrollHeight })
  await page.waitForFunction(() => document.querySelector('tbody')?.textContent.includes('PRJ-10000'))
  assert.ok(await page.locator('tbody tr[data-index]').count() < 80)
  const lastName = page.locator('[data-nav-row="PRJ-10000"][data-nav-column="name"]')
  await lastName.focus(); await lastName.press('F2')
  await editor.fill('Virtual retained draft')
  await viewport.evaluate(element => { element.scrollTop = 0 })
  assert.equal(await editor.inputValue(), 'Virtual retained draft')
  await editor.press('Escape')
  console.log('PASS 10,000 rows render a bounded window, reach final record and keep offscreen drafts mounted')
  await page.getByLabel('Native XLSX export', { exact: true }).check()
  await page.getByLabel('XLSX extra information sheet', { exact: true }).check()
  await page.getByRole('button', { name: 'Export', exact: true }).click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('menuitem', { name: 'XLSX workbook', exact: true }).click()
  const download = await downloadPromise
  assert.match(download.suggestedFilename(), /\.xlsx$/)
  await download.saveAs('evidence/playground-native.xlsx')
  const workbook = new ExcelJS.Workbook()
  await workbook.xlsx.load(await readFile('evidence/playground-native.xlsx'))
  assert.equal(workbook.worksheets.length, 2)
  assert.equal(workbook.getWorksheet('Data').rowCount, 10001)
  const budgetColumn = workbook.getWorksheet('Data').getRow(1).values.indexOf('Budget')
  assert.equal(typeof workbook.getWorksheet('Data').getCell(2, budgetColumn).value, 'number')
  assert.equal(workbook.getWorksheet('Data').getCell(2, budgetColumn).numFmt, '$#,##0.00')
  console.log('PASS native XLSX download includes unrendered rows, numeric cells, formatting and multiple sheets')
  await viewport.evaluate(element => { element.scrollTop = 0 })
  await page.screenshot({ path: 'evidence/advanced-playground.png', fullPage: true })
  assert.deepEqual(errors, [])
} catch (error) {
  await page.screenshot({ path: 'evidence/advanced-failure.png', fullPage: true })
  console.log((await page.locator('body').innerText()).slice(-3500))
  throw error
} finally { await browser.close() }
